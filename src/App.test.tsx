// @vitest-environment jsdom
import { QueryClient, QueryClientProvider } from '@tanstack/react-query'
import { render, screen } from '@testing-library/react'
import { describe, expect, it, vi } from 'vitest'
import App from './App'

describe('digital fairness design review office', () => {
  it('loads readiness cases from the Java API', async () => {
    vi.stubGlobal('fetch', vi.fn().mockResolvedValue({
      ok: true,
      json: async () => [{ id: 1, title: 'Subscription cancellation journey', owner: 'European Digital Commerce Team', status: 'Review', priority: 'High' }],
    }))
    const client = new QueryClient({ defaultOptions: { queries: { retry: false } } })
    render(<QueryClientProvider client={client}><App /></QueryClientProvider>)
    expect(await screen.findByText('Subscription cancellation journey')).toBeTruthy()
    expect(screen.getByRole('heading', { name: 'Digital Fairness Design Review Office' })).toBeTruthy()
  })
})
